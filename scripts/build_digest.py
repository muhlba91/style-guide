#!/usr/bin/env python3
"""Generate the lean digests in common/digest/ from the rule files (`make digest`), or verify them (`--check`).

A digest keeps what an agent needs to apply a rule: ID, strength, the rule sentence, the tool check, and the Good and
Bad lines of `must` rules. Why and Source stay in the full rule file, so every scope, exception and precedence must be
in the Rule sentence. `core.md` holds the `must` rules of the principles plus a few cross-cutting rules and is read for
every task. Quality and effectiveness win over token savings: grow a digest when review shows it loses accuracy.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ("principles", "languages", "writing")
OUT = ROOT / "common" / "digest"
HEADER = re.compile(r"^## ([A-Z][A-Z0-9]*-\d{2}) · (must|prefer|lean) · ([a-z-]+) · (stated|observed|open)\s*$")
FIELD = re.compile(r"^- (Rule|Good|Bad|Check):\s*(.*)$")
AVOID = re.compile(r"^## Avoid \(AI-Era Artifacts\)")
CHECKLIST = re.compile(r"^## New Repository Checklist")
BANNER = "<!-- Generated by scripts/build_digest.py from the rule files. Do not edit. -->\n"
TOKEN_CHARS = 3.6  # rough characters per token for English Markdown
BUDGETS = {"core.md": 2400, "default": 2800}  # tokens per digest file
CORE_EXTRA = ("COMMIT-17", "PR-18", "DOC-06", "DOC-11", "PRIN-16")  # cross-cutting rules outside the principles
REPO_SETUP = ("PRIN-39", "PRIN-41", "PRIN-48", "PRIN-49")  # needed when setting up a repo, not for every task
ARTIFACTS = (
    ("Go, Pulumi", ("languages-go", "languages-pulumi")),
    ("Python", ("languages-python",)),
    ("Shell", ("languages-shell",)),
    ("Kubernetes and Helm YAML", ("languages-yaml", "languages-yaml-kubernetes")),
    ("Workflows", ("languages-github-actions", "languages-yaml")),
    ("Renovate", ("languages-renovate",)),
    ("mise", ("languages-mise",)),
    ("Nix", ("languages-nix",)),
    ("Typst", ("languages-typst",)),
    ("Dockerfile, DNS, Home Assistant YAML", ("languages-config-other", "languages-yaml")),
    ("Makefile", ("languages-makefile",)),
    ("README", ("writing-repo-readme", "writing-prose")),
    ("Runbook, docs", ("writing-runbook", "writing-prose")),
    ("Commit", ("writing-commit",)),
    ("PR, issue", ("writing-pr-issue",)),
    ("Email", ("writing-email",)),
    ("Agent files, AGENTS.md, CHANGELOG, llms.txt", ("writing-prose",)),
    ("Test code (add the language digest)", ("principles-tests",)),
    ("New repo, CI, tooling setup (with the new-repository file checklist)", ("repo-setup",)),
)
PRINCIPLE_TOPICS = (
    "errors-logging", "tests", "naming", "structure", "comments", "tooling", "concision", "tone", "change-hygiene",
)  # fmt: skip


def parse(text):
    """Return (title, rules, avoid) where rules is a list of dicts and avoid the bullets of 'Avoid (AI-Era Artifacts)'."""
    title, rules, avoid, current, in_avoid = "", [], [], None, False
    for line in text.splitlines():
        if line.startswith("# ") and not title:
            title = line[2:].strip()
        header = HEADER.match(line)
        if header:
            current = {"id": header.group(1), "strength": header.group(2), "status": header.group(4)}
            rules.append(current)
            in_avoid = False
            continue
        if line.startswith("## "):
            current = None
            in_avoid = bool(AVOID.match(line))
            continue
        field = FIELD.match(line)
        if current and field:
            current[field.group(1).lower()] = field.group(2).strip()
        elif in_avoid and line.startswith("- "):
            avoid.append(line[2:].strip())
    return title, rules, avoid


def render_rule(rule, with_examples):
    tool = re.match(r"tool:[\w.-]+", rule.get("check", ""))
    check = f" [{tool.group(0)}]" if tool else ""
    lines = [f"- {rule['id']} {rule['strength']}: {rule.get('rule', '')}{check}"]
    if with_examples and rule["strength"] == "must":
        for key in ("good", "bad"):
            if rule.get(key):
                lines.append(f"  {key.capitalize()}: {rule[key]}")
    return "\n".join(lines)


def avoid_block(avoid):
    return ["", "Avoid (AI-Era Artifacts):", ""] + [f"- {item}" for item in dict.fromkeys(avoid)] if avoid else []


def digest_file(path):
    title, rules, avoid = parse(path.read_text(encoding="utf-8"))
    out = [BANNER, f"# {title}\n", "Full rules, evidence and examples: `" + str(path.relative_to(ROOT)) + "`.\n"]
    out += [render_rule(rule, True) for rule in rules]
    return "\n".join(out + avoid_block(avoid)).rstrip() + "\n"


def all_rules(paths):
    rules, avoid = {}, []
    for path in paths:
        _, found, bullets = parse(path.read_text(encoding="utf-8"))
        rules.update({rule["id"]: rule for rule in found})
        avoid += bullets
    return rules, avoid


def rule_files():
    for source in SOURCES:
        for path in sorted((ROOT / "common" / source).glob("*.md")):
            if path.name != "README.md":
                yield source, path


def core_digest(rules, avoid):
    principle_ids = [i for i, r in rules.items() if i.startswith("PRIN-")]
    chosen = [i for i in principle_ids if rules[i]["strength"] == "must" and i not in REPO_SETUP]
    chosen += [i for i in CORE_EXTRA if i in rules and i not in chosen]
    out = [BANNER, "# Core Rules\n", "Read for every task: the `must` rules of the principles (except repo setup, see `repo-setup.md`) and a few cross-cutting rules.\n"]
    out += [render_rule(rules[i], True) for i in chosen]
    return "\n".join(out + avoid_block(avoid)).rstrip() + "\n"


def checklist_bullets():
    """Return the bullets of 'New Repository Checklist' in the principles README (a soft guideline, not rules)."""
    bullets, active = [], False
    for line in (ROOT / "common" / "principles" / "README.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            active = bool(CHECKLIST.match(line))
        elif active and line.startswith("- "):
            bullets.append(line)
    return bullets


def repo_setup_digest(rules):
    out = [BANNER, "# Repo Setup\n", "Read when creating a repo or changing CI and tooling. Full rules: `common/principles/`.\n"]
    out += [render_rule(rules[i], True) for i in REPO_SETUP if i in rules]
    bullets = checklist_bullets()
    if bullets:
        out += ["", "Default files of a new repository (a starting point, not a rule: add what the repo type or language needs, leave out what does not apply, and note nothing when a file is left out):", ""] + bullets
    return "\n".join(out).rstrip() + "\n"


def index_digest(open_count=0):
    rows = ["| Artifact | Digests |", "| --- | --- |"]
    rows += [f"| {name} | {', '.join(f'`{d}.md`' for d in digests)} |" for name, digests in ARTIFACTS]
    topics = ", ".join(f"`principles-{t}.md`" for t in PRINCIPLE_TOPICS)
    return "\n".join(
        [
            BANNER,
            "# Digests\n",
            "Read `core.md` for every task, then the digests for the artifacts. A rule's Why and Source are not in a digest: "
            "read the full rule when a rule is unclear or you need its evidence "
            "(`grep -rn -A10 '^## <ID> ' common/languages common/writing common/principles`).\n",
            *rows,
            "",
            f"Add a principles digest only when the task needs it: {topics}. `core.md` holds their `must` rules, except the repo-setup ones.",
            "",
            "Legend:",
            "",
            "- `[tool:x]`: a configured tool in the owner's repos enforces the rule.",
            "- A digest shows strength only. "
            + ("No rule is `open`: every decision is made." if not open_count else f"{open_count} rules are `open`: see `OPEN-QUESTIONS.md`."),
            "- A rule for new files or scripts applies to files created or substantially rewritten; existing files stay unless touched.",
            "- Pulumi program: a repo that deploys stacks (github-infrastructure, vault, home-cluster infrastructure). Pulumi library: a reusable Go package of resources (shared-library).",
            "- IaC and config repo: deploys or configures infrastructure. Library and client repo: a published package (shared-library, onyx-client).",
        ]
    ) + "\n"


def build():
    rules, _ = all_rules(path for _, path in rule_files())
    _, avoid = all_rules([ROOT / "common" / "principles" / "README.md"])
    files = {"core.md": core_digest(rules, avoid), "repo-setup.md": repo_setup_digest(rules), "README.md": index_digest(sum(r["status"] == "open" for r in rules.values()))}
    for source, path in rule_files():
        files[f"{source}-{path.name}"] = digest_file(path)
    return files


def tokens(text):
    return round(len(text) / TOKEN_CHARS)


def main(argv):
    files = build()
    problems = []
    for name, text in files.items():
        budget = BUDGETS.get(name, BUDGETS["default"])
        if tokens(text) > budget:
            problems.append(f"{name}: about {tokens(text)} tokens, budget {budget}")
    for _, digests in ARTIFACTS:
        problems += [f"lookup table names {d}.md which does not exist" for d in digests if f"{d}.md" not in files]
    if "--check" in argv:
        for name, text in files.items():
            target = OUT / name
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                problems.append(f"{name}: stale, run make digest")
        existing = {p.name for p in OUT.glob("*.md")} if OUT.is_dir() else set()
        problems += [f"{name}: no source, delete it" for name in sorted(existing - set(files))]
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (OUT / name).write_text(text, encoding="utf-8")
        for stale in sorted({p.name for p in OUT.glob("*.md")} - set(files)):
            (OUT / stale).unlink()
    sizes = ", ".join(f"{n.removesuffix('.md')}:{tokens(t)}" for n, t in files.items())
    print(f"digest tokens (about): {sizes}")
    for problem in problems:
        print(f"ERROR {problem}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
